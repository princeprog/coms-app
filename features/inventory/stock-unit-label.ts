// Units are free text; retain custom labels instead of guessing their meaning.
export function stockUnitLabel(unit: string) {
  const value = unit.trim();
  const key = value.toLowerCase().replace(/\.$/, "");
  return Object.hasOwn(unitNames, key) ? unitNames[key] : value;
}
